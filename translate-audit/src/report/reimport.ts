import { writeFileSync } from "node:fs";
import type { ReviewedRow } from "./xlsx.ts";

const csvCell = (s: string): string => (/[",\n\r]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s);

export type ReimportRow = { entryId: string; keyName: string; lang: string; before: string; after: string };

export function selectChanges(rows: ReviewedRow[]): ReimportRow[] {
  const out: ReimportRow[] = [];
  for (const r of rows) {
    if (r.decision !== "accept" && r.decision !== "edited") continue;
    const after = r.final.trim();
    if (!after || after === r.current.trim()) continue;
    out.push({ entryId: r.entryId, keyName: r.keyName, lang: r.lang, before: r.current, after });
  }
  return out;
}

export function writeReimportCsv(path: string, rows: ReimportRow[]): void {
  const lines = ["key_id,key_name,language_iso,translation,previous_translation"];
  for (const r of rows) {
    lines.push([r.entryId, r.keyName, r.lang, r.after, r.before].map(csvCell).join(","));
  }
  writeFileSync(path, "﻿" + lines.join("\n") + "\n", "utf8");
}

export function writeMongoScript(path: string, rows: ReimportRow[], dbName: string): void {
  const lines = [
    "// Generated by translate-audit. Review before running.",
    `// ${rows.length} translation${rows.length === 1 ? "" : "s"} accepted by a human reviewer.`,
    `const target = db.getSiblingDB(${JSON.stringify(dbName)});`,
    "let updated = 0;",
  ];
  for (const r of rows) {
    lines.push(
      `updated += target.Translations.updateOne(` +
        `{ keyId: ObjectId(${JSON.stringify(r.entryId)}), langIso: ${JSON.stringify(r.lang)} }, ` +
        `{ $set: { value: ${JSON.stringify(r.after)}, status: "unverified", modifiedBy: "translate-audit", modifiedAt: new Date() } }` +
        `).modifiedCount;`,
    );
  }
  lines.push('print("updated " + updated + " translations");');
  writeFileSync(path, lines.join("\n") + "\n", "utf8");
}
